# -*- coding: utf-8 -*-
"""
publish.py -- turn a built layout into a deployable system package.

The builder saves a layout this master serves immediately. Publishing is the
other half: the same layout, packaged as `systems/<slug>/` that any deployment
can drop into its own repo -- so what an operator composed in a browser is
something an engineer can review, commit, and ship.

The generated `system.py` contains **no generated logic**. It loads its
`layout.json` and hands the widget dicts to `core.services.builder`, which is
the code that was already rendering them. Generating Python from user input and
importing it back is how a dashboard builder becomes an RCE; this keeps the
data as data on both sides of the export.
"""

import io
import json
import os
import re
import zipfile

from core.services import builder

SLUG_RE = re.compile(r"^[a-z][a-z0-9_]*$")

# The "generated by the IRIV Vision Studio builder" line below is NOT a stale
# product name: provision._GENERATED_MARKER keys removal on it, and packages
# already on boxes carry it. Change both or neither.
_SYSTEM_PY = '''# -*- coding: utf-8 -*-
"""
system.py - generated by the IRIV Vision Studio builder. Safe to edit by hand.

The widgets live in layout.json beside this file. Each one names a source and a
key; core.services.builder reads those out of the standard stats/events. Add a
hand-written WidgetSpec below when a widget needs real logic - the two kinds
coexist, and hand-written ones win on a duplicate id.
"""

import json
import os

from core.services import builder
from core.system_spec import SystemSpec, WidgetSpec

_HERE = os.path.dirname(os.path.abspath(__file__))


def _layout():
    with open(os.path.join(_HERE, "layout.json"), "r", encoding="utf-8") as f:
        return json.load(f).get("widgets", [])


def _widget(spec):
    """One declarative widget -> a WidgetSpec whose data_fn is the shared,
    audited renderer. No exec, no eval, no generated logic.

    Capability gating is the WidgetSpec's job (the outer layer filters on it);
    it is stripped before builder.compute, which would otherwise re-filter the
    widget out and leave an empty list - an IndexError, not a gated widget."""
    return WidgetSpec(
        id=spec["id"],
        title=spec["title"],
        kind=spec["kind"],
        capability=spec.get("capability", ""),
        span=spec.get("span", 1),
        data_fn=lambda events, stats, _s=spec: builder.compute(
            [dict(_s, capability="")], events, stats)[0]["data"],
    )


SPEC = SystemSpec(
    slug={slug!r},
    display_name={display_name!r},
    subtitle={subtitle!r},
    icon={icon!r},
    cover={cover!r},
    order={order},
    analytics=tuple(_widget(w) for w in _layout()),
)
'''

_README = """# {display_name}

Generated by the IRIV Edge AI Studio builder.

    systems/{slug}/
      system.py     master-side SPEC - reads layout.json
      layout.json   the widgets, as data. Edit here or re-publish from the UI.
      config.toml   the detection app's config (if this system ships one)

## Install

1. Copy this folder into your deployment's systems directory (the one
   `[systems].dir` points at).
2. Add the slug to `[systems].enabled` and give it a master URL:

       enabled = [..., "{slug}"]

       [masters.{slug}]
       url = "http://127.0.0.1:{port}"

3. Start that system's master:

       python master_server.py --system {slug} --port {port}

The hub card, the nav and these widgets appear. No product file is edited.

## Devices

Widgets read the standard stats keys and event envelope, so any device whose
adapter passes `tools/contract_check.py` feeds them. A widget bound to a key no
device publishes renders empty - that is the adapter's job to fix, not this
package's.
"""


def package(slug, layout, meta=None, port=5110):
    """Return (filename, zip_bytes) for a downloadable system package."""
    if not SLUG_RE.match(slug or ""):
        raise ValueError("slug must be lowercase letters, digits and underscores, "
                         "starting with a letter")
    widgets = builder.validate((layout or {}).get("widgets"))
    meta = meta or {}
    display_name = str(meta.get("display_name") or slug.replace("_", " ").title())[:60]

    system_py = _SYSTEM_PY.format(
        slug=slug,
        display_name=display_name,
        subtitle=str(meta.get("subtitle") or "")[:60],
        icon=str(meta.get("icon") or display_name[:1].upper())[:2],
        cover=str(meta.get("cover") or "cover-a"),
        order=int(meta.get("order") or 100),
    )
    readme = _README.format(display_name=display_name, slug=slug, port=int(port))
    layout_json = json.dumps({"slug": slug, "widgets": widgets}, indent=2)

    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr(f"{slug}/system.py", system_py)
        z.writestr(f"{slug}/layout.json", layout_json)
        z.writestr(f"{slug}/README.md", readme)
    return f"{slug}-system-package.zip", buf.getvalue()


def write_package(systems_dir, slug, layout, meta=None, overwrite=False):
    """Write the same package straight into this host's systems directory.

    Refuses to overwrite by default: publishing must never silently replace a
    hand-written package someone is maintaining.
    """
    if not SLUG_RE.match(slug or ""):
        raise ValueError("invalid slug")
    target = os.path.join(systems_dir, slug)
    system_py = os.path.join(target, "system.py")
    if os.path.exists(system_py) and not overwrite:
        raise ValueError(f"{slug} already exists; publish with overwrite to replace it")

    _, blob = package(slug, layout, meta)
    os.makedirs(target, exist_ok=True)
    with zipfile.ZipFile(io.BytesIO(blob)) as z:
        for name in z.namelist():
            rel = name.split("/", 1)[1]
            if not rel:
                continue
            dest = os.path.join(target, rel)
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            with open(dest, "wb") as f:
                f.write(z.read(name))
    return target
