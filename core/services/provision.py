def set_format_label(key, label, config_dir=None):
    """Rename a published template, everything else untouched. Returns True
    when a format by that key existed. The hub calls this when the SYSTEM a
    template was published from is renamed: the card in the folder and the
    card in the create wizard are one template, and read one name."""
    key = str(key or "").strip().lower()
    label = " ".join(str(label or "").split())[:60]
    formats = dict((config.load(FORMATS_FILE, config_dir) or {}).get("formats") or {})
    if key not in formats or not label:
        return False
    entry = dict(formats[key])
    if entry.get("label") == label:
        return True
    entry["label"] = label
    formats[key] = entry
    _write_formats(formats, config_dir)
    return True


def forget_format(key, config_dir=None):
    """Drop a template and its workbench link because the SYSTEM it was
    published from is gone. Unlike delete_format this never refuses -- a
    template whose authoring system was deleted is not a choice anybody made
    about the template, and keeping it would leave the create wizard
    offering a card the folder no longer shows. Returns True if one went.

    The blank canvas is the exception, here as everywhere: deleting the
    system it was published from unlinks the workbench and keeps the
    template, because a box that cannot start from empty is not a state any
    action should be able to produce."""
    key = str(key or "").strip().lower()
    if key == PROTECTED_FORMAT:
        set_format_workbench(key, "", config_dir)
        return False
    formats = dict((config.load(FORMATS_FILE, config_dir) or {}).get("formats") or {})
    went = key in formats
    if went:
        formats.pop(key)
        _write_formats(formats, config_dir)
    set_format_workbench(key, "", config_dir)
    return went


def set_format_workbench(key, slug, config_dir=None):
    local = dict(config.load_local(WORKBENCH_FILE, config_dir) or {})
    formats = dict(local.get("formats") or {})
    if slug:
        formats[str(key)] = str(slug)
    else:
        formats.pop(str(key), None)
    local["formats"] = formats
    config.save_local(WORKBENCH_FILE, local, config_dir)
    return formats


#: Serialises every rewrite of formats.toml. Re-entrant because save_format
#: holds it across its read-modify-write and _write_formats takes it again.
_FORMATS_LOCK = threading.RLock()


def _write_formats(formats, config_dir=None):
    """Write config/formats.toml. See the banner above for why this one
    committed file is API-writable.

    Written the way config.save_local writes: to a sibling temp file, swapped
    in with os.replace, so a crash or a power cut mid-write leaves the old
    file whole rather than a truncated one. And READ BACK before the swap: a
    formats.toml that does not parse is a box with no templates and no page
    that can write one, because every writer loads the file first -- so a
    text that would not parse is refused here, with the old file untouched.
    """
    base = config.root(config_dir)
    base.mkdir(parents=True, exist_ok=True)
    header = (
        "# formats.toml - built-in detection formats authored on this box.\n"
        "#\n"
        "# Written by the System Templates page (developer accounts only) and\n"
        "# COMMITTED on purpose: a format authored here is meant to ship.\n"
        "# Keys absent here fall back to core/services/provision.py TEMPLATES.\n\n"
    )
    text = header + config._toml_dump({"formats": formats}) + "\n"
    try:
        tomllib.loads(text)
    except tomllib.TOMLDecodeError as exc:
        raise ValueError(f"the templates would not read back as TOML: {exc}")
    path = base / (FORMATS_FILE + ".toml")
    tmp = path.with_name(path.name + ".tmp")
    with _FORMATS_LOCK:
        tmp.write_text(text, encoding="utf-8")
        os.replace(tmp, path)
    config.load.cache_clear()


