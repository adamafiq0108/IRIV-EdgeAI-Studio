def _slugify(name):
    s = re.sub(r"[^a-z0-9]+", "_", str(name or "").lower()).strip("_")
    if not s:
        return ""
    return s if s[0].isalpha() else "s_" + s


def _lan_ip():
    """This host's LAN address -- the one a laptop on the same network reaches
    it by. The UDP connect sends no packet; it only asks the kernel which local
    interface would route outward. Empty string if it cannot be determined."""
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        try:
            s.connect(("192.0.2.1", 9))
            ip = s.getsockname()[0]
        finally:
            s.close()
        if ip and not ip.startswith("127."):
            return ip
    except OSError:
        pass
    return ""


def _master_host(cfg):                                      # noqa: ARG001
    """The host a new master's url is STORED with: always loopback.

    Masters always run on the same box as the hub, so the stored address only
    ever needs to reach this machine. Storing the LAN ip instead used to seem
    friendlier -- until DHCP moved the board and every system became
    "runs at <old ip> -- manage it on that host", uncontrollable from its own
    hub. What a browser sees is a separate question, answered at render time by
    core/net.py rewrite(), which puts each card on whatever host the operator
    typed. Config holds the durable fact; the URL bar holds the situational one.
    """
    return "127.0.0.1"


def heal_master_hosts(config_dir=None):
    """Repoint any master url whose host is no longer this box at loopback.

    A config written before the rule above -- or on a board that has since
    changed address -- names a host that may now be a DIFFERENT machine. The
    port is the part that identifies the master; the host is incidental, so it
    is safe to correct and unsafe to leave. Returns the slugs healed.
    """
    cfg = config.systems(config_dir)
    masters = cfg.get("masters") or {}
    healed = []
    local = None
    for slug, entry in masters.items():
        url = (entry or {}).get("url") or ""
        parsed = urllib.parse.urlparse(url)
        host = parsed.hostname
        if not host or not parsed.port:
            continue
        if host in ("127.0.0.1", "localhost") or is_local_master(host):
            continue
        if local is None:
            local = config.load_local("systems", config_dir)
        target = local.setdefault("masters", {}).setdefault(slug, {})
        target.update(entry or {})
        target["url"] = f"http://127.0.0.1:{parsed.port}"
        healed.append(slug)
    if healed:
        config.save_local("systems", local, config_dir)
    return healed


def _ports_in_use(cfg):
    """Every port config already hands out. The hub's own port counts -- handing
    it out would be a card that links to the hub."""
    ports = set()
    for entry in (cfg.get("masters") or {}).values():
        parsed = urllib.parse.urlparse((entry or {}).get("url") or "")
        if parsed.port:
            ports.add(parsed.port)
    hub = urllib.parse.urlparse((cfg.get("hub") or {}).get("url") or "")
    if hub.port:
        ports.add(hub.port)
    try:                    # ...and the port it is SAVED to move to at restart
        ports.add(int((cfg.get("hub") or {}).get("pending_port") or 0) or hub.port)
    except (TypeError, ValueError):
        pass
    ports.discard(None)
    return ports


def _port_is_free(port):
    """True if nothing on this box listens on `port`. Guards against a zombie
    master (one a failed Remove left running) squatting on a port the config
    no longer knows about -- binding is the only honest test."""
    s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    try:
        s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        s.bind(("0.0.0.0", int(port)))
        return True
    except OSError:
        return False
    finally:
        s.close()


#: Masters live at 5110 and up -- the port scripts/install.sh gives the first
#: built-in system's unit. Below it are the hub (5100), the device agent (5101)
#: and demo's video stream (5102). The allocator used to count up from the
#: highest port in use, and on a fresh box the only port in use is the hub's,
#: so demo was handed 5101 (the agent's) while its unit ran on 5110 -- a red
#: "down" card -- and the next system got 5102, demo's stream port.
MASTER_PORT_BASE = 5110

#: A detection app's MJPEG port when its config names none; mirrors
#: detector_control.DEFAULT_STREAM_PORT (not imported: that module is heavy and
#: imports this one lazily).
_DEFAULT_STREAM_PORT = 5102


def _default_systems_dir(config_dir=None):
    """The built-in systems dir the hub scans, resolved the way hub_server does."""
    d = pathlib.Path(config.systems(config_dir).get("dir", "systems"))
    return d if d.is_absolute() else pathlib.Path(__file__).resolve().parents[2] / d


def stream_ports_in_use(systems_dir=None, config_dir=None):
    """Every port a system's detection app serves its MJPEG stream on.

    A master and a stream app are both plain listeners on this box, so a port
    one holds is a port the other must never be handed. Read from each
    package's config.toml + config.local.toml [app].stream_port, the same
    files detector_control.stream_port() reads. The scan itself is
    sysport.stream_port_owners, which also says WHOSE stream it is.
    """
    from core.services import sysport                      # noqa: PLC0415
    return set(sysport.stream_port_owners(systems_dir, config_dir))


def modbus_ports_in_use(systems_dir=None, config_dir=None):
    """{port: slug} for every system whose Modbus TCP server is switched on.

    Read from each package's config.toml + config.local.toml
    [modbus_server], the files detector_control.get_modbus_server() reads.
    A listener only exists when the server is enabled in tcp or both mode, so
    only those hold a port.
    """
    out = {}
    root = systems_dir or _default_systems_dir(config_dir)
    for slug, pkg in system_slugs(root, config_dir).items():
        ms = {}
        for name in ("config.toml", "config.local.toml"):
            try:
                with open(os.path.join(pkg, name), "rb") as f:
                    ms.update(tomllib.load(f).get("modbus_server") or {})
            except (OSError, tomllib.TOMLDecodeError):
                continue
        if not ms.get("enabled") or str(ms.get("mode") or "tcp") not in ("tcp", "both"):
            continue
        try:
            out.setdefault(int(ms.get("port") or 5020), slug)
        except (TypeError, ValueError):
            continue
    return out


def unit_ports():
    """{port: slug} for every installed irivai-master@<slug> unit, from
    /etc/irivai/<slug>.env -- running or not, enabled or not.

    A unit's port is taken even while nothing listens on it. Box .164
    (2026-10-09): demo's unit had been stopped when system "z" was created,
    so 5110 was free at that moment and z got it; at the next boot systemd
    started demo and the hub started z, both on 5110, and whichever bound
    first answered as the other. The config did not know the port either
    (demo was not in [masters] any more), so _ports_in_use missed it too.
    """
    out = {}
    try:
        names = os.listdir(UNIT_ENV_DIR)
    except OSError:
        return out
    for name in names:
        if not name.endswith(".env"):
            continue
        slug = name[:-4]
        port = _unit_port(slug)
        if port:
            out.setdefault(port, slug)
    return out


def _taken_ports(cfg, systems_dir=None, config_dir=None):
    """Every port no new master or stream may take: masters, the hub, every
    system's stream port, every switched-on Modbus server, every installed
    master unit's port (bound or not), and the box's own services
    (hubport.RESERVED, which holds 5020, the 502 redirect's target)."""
    from core.services import hubport                      # noqa: PLC0415
    return (_ports_in_use(cfg) | stream_ports_in_use(systems_dir, config_dir)
            | set(modbus_ports_in_use(systems_dir, config_dir))
            | set(unit_ports()) | set(hubport.RESERVED))


def next_master_url(cfg, systems_dir=None, config_dir=None):
    """The url a new master gets: the shared host, next port after the highest
    master port (never below MASTER_PORT_BASE) -- skipping every port another
    master, the hub, a system's video stream or a box service holds, and
    ports something already listens on. The config is not the whole truth: a
    stale master from a deleted system may still hold a port the config freed,
    and handing that port to a new system makes its card answer as the DEAD
    one."""
    taken = _taken_ports(cfg, systems_dir, config_dir)
    port = max({p for p in _ports_in_use(cfg) if p >= MASTER_PORT_BASE}
               or {MASTER_PORT_BASE - 1}) + 1
    for _ in range(200):
        if port not in taken and _port_is_free(port):
            break
        port += 1
    return f"http://{_master_host(cfg)}:{port}", port


def next_stream_port(master_port, cfg, systems_dir=None, config_dir=None):
    """A new system's stream port: master + 100 (5210 for the master at 5110),
    stepped past anything already taken -- including the new master itself."""
    taken = _taken_ports(cfg, systems_dir, config_dir) | {int(master_port)}
    port = int(master_port) + 100
    for _ in range(200):
        if port not in taken and _port_is_free(port):
            break
        port += 1
    return port


