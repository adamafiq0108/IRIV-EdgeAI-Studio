def system_slugs(systems_dir, config_dir=None):
    """Every system package on this box, as {slug: package_dir}.

    Reads folders, not imported SPECs: this runs before a create, where a
    package that fails to import still occupies a slot. Mirrors
    registry.discover's roots (built-in dir honouring [systems].enabled, then
    the generated store), de-duplicated by slug the same way.
    """
    enabled = config.systems(config_dir).get("enabled")
    found = {}
    roots = [(str(systems_dir), True), (str(config.generated_systems_dir()), False)]
    for root, apply_enabled in roots:
        try:
            children = sorted(os.listdir(root))
        except OSError:
            continue
        for name in children:
            if name.startswith((".", "_")) or name in found:
                continue
            if not os.path.exists(os.path.join(root, name, "system.py")):
                continue
            if apply_enabled and enabled is not None and name not in enabled:
                continue
            found[name] = os.path.join(root, name)
    return found


def count_systems(systems_dir, config_dir=None):
    """How many system packages this box holds."""
    return len(system_slugs(systems_dir, config_dir))

# Detection-format templates.
#
# There used to be nine of them here, as code: "Violation detection", "PPE
# detection", "Handrail detection"... each a label, a hint and a dozen widgets
# bound to the generic stat keys, and none carrying a workflow. They were the
# product's starter kit before templates could be AUTHORED, and once they
# could -- a system filed under the hub's "Built-in templates" folder is
# snapshotted, workflow and dashboard and zones and all, into
# config/formats.toml -- the code list became the thing standing between the
# operator and the list they had curated: nine stale cards beside the four
# real ones, told apart by nothing.
#
# So the code ships NO formats. config/formats.toml is the whole list, and it
# is a TRACKED file (see _write_formats): what the developer box publishes is
# what the next release carries, and every box on that release offers exactly
# those templates in its create wizard. The hub folder and the wizard are one
# list, edited in one place.
#
# Kept as an (empty) dict rather than removed: builtin_formats() still layers
# the file over it, so a future shipped-in-code format has a place to go, and
# every `key in TEMPLATES` test below keeps meaning "the product ships this".
TEMPLATES = {}

#: The template a caller gets when it names none -- see default_template().
#: With nothing shipped in code it is a preference, not a promise: the blank
#: canvas where one is published under this key, else the first published.
DEFAULT_TEMPLATE = "blank_canvas"

#: What a system created from a template needs drawn before its analytics can
#: say anything. A published template's own zone guidance (captured from the
#: authoring system) wins; this is the answer when it carries none.
_BLANK_ZONE = {"mode": "optional",
               "hint": "Add zones on the Detection page if you want zone-based "
                       "counts or violations."}
ZONE_GUIDANCE = {"blank_canvas": _BLANK_ZONE}

#: Default class filter per shipped template. Empty with TEMPLATES; a
#: published template carries its own class list from the system it was
#: snapshotted from.
TEMPLATE_CLASSES = {}
_DEFAULT_CLASSES = ["person"]

#: The system that is no template at all: what a create gets when it names
#: nothing and nothing is published. Empty dashboard, default class filter,
#: no model preset -- the blank canvas, as code rather than as content, for
#: the one path (a store install on a box with no formats) that must not
#: depend on content being there.
BARE_FORMAT = {"label": "Blank canvas", "hint": "", "widgets": [],
               "zone": dict(_BLANK_ZONE), "classes": list(_DEFAULT_CLASSES),
               "category": "built-in",
               "model": "", "shipped": False, "edited": False, "hidden": False,
               "draft": False, "has_workflow": False}


# ---------------------------------------------------------------------------
# Built-in formats, as EDITABLE data
#
# The dicts above are the formats this product ships with. A DEVELOPER may
# override any of them and add new ones; those edits live in
# config/formats.toml -- a TRACKED file, deliberately, because a built-in
# format is product content. The whole point of authoring one is that it ships
# to the next deployment, which a gitignored file could never do.
#
# This is the one place the codebase writes a committed file from an API
# (config.save_local exists precisely to avoid that). It is justified by WHO
# can reach it: the developer tier cannot be granted over the web at all (see
# auth.DEVELOPER_FLAG), so "an API wrote a tracked file" still means "the
# person with shell access to this box edited it", through a form rather than
# a text editor. No other role can call these functions.
#
# The code dicts stay as the base layer rather than being migrated into the
# file, so a deployment that authors nothing behaves exactly as before, and an
# unreadable formats.toml degrades to the shipped set instead of leaving the
# product with no formats at all.
# ---------------------------------------------------------------------------

FORMATS_FILE = "formats"

#: Zone modes a format may declare. Anything else is refused rather than
#: quietly treated as "blank", which would drop a format's zone requirement.
ZONE_MODES = ("none", "area", "line", "area_line", "optional")

#: The detection model a template starts with. Every template EXCEPT the blank
#: canvas presets one, so a created system needs nothing but a camera to run:
#: the model is selected and its HEF fetched at create time. Blank canvas is
#: deliberately bare -- it exists for people who bring their own model.
DEFAULT_TEMPLATE_MODEL = "yolov8n"
NO_MODEL_TEMPLATES = ("blank",)

#: The folder a format lands in when its author names none. Formats are
#: grouped the same way saved templates are, so one page teaches one idea.
DEFAULT_FORMAT_CATEGORY = "built-in"

#: A format key may be HIDDEN rather than deleted when the product ships it --
#: code is the floor and cannot be edited from a board. The tombstone lives in
#: the same file as the overrides.
_HIDDEN_KEY = "hidden"

_FORMAT_KEY_RE = re.compile(r"^[a-z][a-z0-9_]{0,31}$")


def _formats_overlay(config_dir=None):
    """The developer's authored/overridden formats, or {} when unreadable.

    Unreadable is not fatal on purpose: a bad file must not take the
    create-a-system flow down with it. The shipped formats stand and the
    operator can still build something.
    """
    try:
        raw = config.load(FORMATS_FILE, config_dir) or {}
    except Exception:                                        # noqa: BLE001
        return {}
    out = {}
    for key, entry in (raw.get("formats") or {}).items():
        if isinstance(entry, dict) and str(key).strip():
            out[str(key).strip()] = entry
    return out


def _format_category(value):
    """A single folder segment, or the default. Formats nest one level only:
    the picker is a flat two-pane list, and deeper folders would be a tree
    nobody asked for."""
    seg = str(value or "").strip().strip("/").replace("\\", "/").split("/")[0]
    seg = re.sub(r"[^A-Za-z0-9 _-]", "", seg).strip()
    return seg[:40] or DEFAULT_FORMAT_CATEGORY


def builtin_formats(config_dir=None, include_hidden=False):
    """Every built-in format: the shipped ones, overlaid with the developer's.

    One record per format -- {label, hint, widgets, zone: {mode, hint},
    classes, shipped, edited} -- so a caller never has to join four dicts to
    answer a question about one format.
    """
    overlay = _formats_overlay(config_dir)
    keys = list(TEMPLATES) + [k for k in overlay if k not in TEMPLATES]
    out = {}
    for key in keys:
        base = TEMPLATES.get(key) or {}
        over = overlay.get(key) or {}
        # A shipped format the developer removed. Kept as a tombstone because
        # the code dict cannot be edited on a board -- without this, "delete"
        # on a shipped format could only ever mean "revert".
        if over.get(_HIDDEN_KEY) and not include_hidden:
            continue
        zone = dict(ZONE_GUIDANCE.get(key) or _BLANK_ZONE)
        zone.update({k: v for k, v in (over.get("zone") or {}).items()
                     if k in ("mode", "hint")})
        out[key] = {
            "label": over.get("label") or base.get("label") or key,
            "hint": (over.get("hint") if over.get("hint") is not None
                     else base.get("hint", "")),
            "widgets": (over.get("widgets") if over.get("widgets") is not None
                        else list(base.get("widgets") or [])),
            "zone": zone,
            "classes": (over.get("classes") if over.get("classes") is not None
                        else list(TEMPLATE_CLASSES.get(key) or _DEFAULT_CLASSES)),
            # `shipped` = the product ships it, so deleting only drops the
            # override. `edited` = a developer changed or added it.
            "category": _format_category(
                over.get("category")
                or (DEFAULT_FORMAT_CATEGORY if key in TEMPLATES else None)),
            # The detection model a system created from this template starts
            # with. "" = none (blank canvas, or a template deliberately left
            # modelless). An author's choice wins over the shipped default.
            "model": str(over.get("model") if over.get("model") is not None
                         else ("" if key in NO_MODEL_TEMPLATES
                               else DEFAULT_TEMPLATE_MODEL)),
            "shipped": key in TEMPLATES,
            "edited": key in overlay,
            "hidden": bool(over.get(_HIDDEN_KEY)),
            # A DRAFT is the developer's work in progress: fully editable
            # through its workbench, but not yet offered to admins in the
            # create picker. "Move to built-in" clears the flag.
            "draft": bool(over.get("draft")),
        }
        # A published format may carry a whole WORKFLOW (stored as a JSON
        # string: the graph nests too deep to trust the TOML writer with).
        # Systems created from the format start with it applied.
        wf = over.get("workflows_json")
        if wf:
            try:
                out[key]["workflows"] = json.loads(wf)
            except (TypeError, ValueError):
                out[key]["workflows"] = None
        out[key]["has_workflow"] = bool(out[key].get("workflows"))
        dash = over.get("dashboard_json")
        if dash:
            try:
                out[key]["dashboard"] = json.loads(dash)
            except (TypeError, ValueError):
                out[key]["dashboard"] = None
        tbl = over.get("tables_json")
        if tbl:
            try:
                out[key]["tables"] = json.loads(tbl)
            except (TypeError, ValueError):
                out[key]["tables"] = None
        for blob_key, name in (("zones_json", "zones"),
                               ("settings_json", "settings")):
            blob = over.get(blob_key)
            if blob:
                try:
                    out[key][name] = json.loads(blob)
                except (TypeError, ValueError):
                    out[key][name] = None
    return out


def default_template(config_dir=None):
    """The template a create names when it names none: "blank" where one is
    published under that key, else the first published one, else "" -- and
    "" is what tells the wizard there is nothing to offer yet, rather than a
    key that will be refused at create time."""
    formats = builtin_formats(config_dir)
    live = [k for k, f in formats.items() if not f.get("draft")]
    if DEFAULT_TEMPLATE in live:
        return DEFAULT_TEMPLATE
    return live[0] if live else ""


def format_key(slug):
    """The format a system publishes as. One system, one format, republish
    idempotent -- so the key is the slug, normalised the way format keys are.

    A `_template_editor` suffix is dropped: the developer box names its
    authoring systems `counting_template_editor`, and the template that
    system IS is called `counting`. The suffix says how the system is used
    on that box, not what the template is, and it would otherwise reach every
    customer's create wizard as the key under the card."""
    key = str(slug or "").strip().lower().replace("-", "_")
    for suffix in ("_template_editor", "_template"):
        if key.endswith(suffix) and len(key) > len(suffix):
            key = key[:-len(suffix)]
            break
    return key


def format_categories(config_dir=None):
    """Every folder formats live in, including empty ones an author made."""
    cats = {DEFAULT_FORMAT_CATEGORY}
    for f in builtin_formats(config_dir).values():
        cats.add(f["category"])
    for entry in _formats_overlay(config_dir).values():
        if isinstance(entry, dict) and entry.get("category"):
            cats.add(_format_category(entry["category"]))
    return sorted(cats)


def format_entry(key, data):
    """Validate `data` into the record formats.toml stores, without writing.

    save_format is this plus the write. It stands alone so the template
    updater (services/template_updates.py) can put a PUBLISHED template
    through the same validation and compare the result with the local record
    in the one shape both have -- a comparison of the raw files would call
    every re-serialised blob a change.

    Validated rather than trusted: these records drive system creation, so a
    malformed one would not fail here -- it would fail later, on a board, while
    somebody was trying to build a system. Returns (key, entry).
    """
    key = str(key or "").strip().lower()
    if not _FORMAT_KEY_RE.match(key):
        raise ValueError("a format key is lowercase letters, digits and "
                         "underscores, starting with a letter")
    if not isinstance(data, dict):
        raise ValueError("a format must be an object")

    label = str(data.get("label") or "").strip()
    if not label:
        raise ValueError("a format needs a label")

    entry = {"label": label[:80],
             "hint": str(data.get("hint") or "").strip()[:300],
             "category": _format_category(data.get("category"))}

    # The starting detection model. Stored as a plain catalogue/model name;
    # whether this box HAS it is a question for create time, not save time --
    # a template is authored once and created from on many boxes.
    if data.get("model") is not None:
        model = str(data.get("model") or "").strip().lower()
        if model and not re.match(r"^[a-z0-9][a-z0-9_.-]{0,39}$", model):
            raise ValueError("a model name is lowercase letters, digits, "
                             "dot, dash and underscore")
        entry["model"] = model

    zone = data.get("zone") or {}
    if not isinstance(zone, dict):
        raise ValueError("zone must be an object with a mode and a hint")
    mode = str(zone.get("mode") or "optional").strip().lower()
    if mode not in ZONE_MODES:
        raise ValueError("zone mode must be one of " + ", ".join(ZONE_MODES))
    entry["zone"] = {"mode": mode,
                     "hint": str(zone.get("hint") or "").strip()[:300]}

    classes = data.get("classes")
    if classes is not None:
        if not isinstance(classes, list):
            raise ValueError("classes must be a list")
        entry["classes"] = [str(c).strip() for c in classes if str(c).strip()][:50]

    widgets = data.get("widgets")
    if widgets is not None:
        if not isinstance(widgets, list):
            raise ValueError("widgets must be a list")
        for w in widgets:
            if not isinstance(w, dict) or not str(w.get("id") or "").strip():
                raise ValueError("every widget needs an id")
        entry["widgets"] = widgets[:40]

    # A whole workflow store, published from a working system. Stored as a
    # JSON string: the graph nests deeper than the TOML writer is trusted
    # with, and it round-trips byte-exact this way.
    workflows = data.get("workflows")
    if workflows:
        if not isinstance(workflows, dict) or not isinstance(
                workflows.get("workflows"), list):
            raise ValueError("workflows must be a workflow store object")
        blob = json.dumps(workflows, separators=(",", ":"))
        if len(blob) > 256 * 1024:
            raise ValueError("the format's workflow is larger than 256 KB")
        entry["workflows_json"] = blob

    # The dashboard layout, same treatment and for the same reason: it nests
    # deeper than the TOML writer is trusted with. Validated properly when it
    # is APPLIED (apply_template runs it through builder.validate); here it
    # only has to be a plausible layout object.
    dashboard = data.get("dashboard")
    if dashboard:
        if not isinstance(dashboard, dict):
            raise ValueError("dashboard must be a layout object")
        blob = json.dumps(dashboard, separators=(",", ":"))
        if len(blob) > 256 * 1024:
            raise ValueError("the format's dashboard is larger than 256 KB")
        entry["dashboard_json"] = blob

    tables = data.get("tables")
    if tables:
        if not isinstance(tables, list):
            raise ValueError("tables must be a list of table definitions")
        entry["tables_json"] = json.dumps(tables, separators=(",", ":"))[:64 * 1024]

    # The zones and the on-system settings (capture switches, status-box
    # rows): the rest of "duplicate everything except the data". JSON blobs
    # like the workflow, for the same TOML-nesting reason.
    zones = data.get("zones")
    if zones:
        if not isinstance(zones, list):
            raise ValueError("zones must be a list")
        blob = json.dumps(zones, separators=(",", ":"))
        if len(blob) > 128 * 1024:
            raise ValueError("the format's zones are larger than 128 KB")
        entry["zones_json"] = blob
    settings = data.get("settings")
    if settings:
        if not isinstance(settings, dict):
            raise ValueError("settings must be an object")
        entry["settings_json"] = json.dumps(settings,
                                            separators=(",", ":"))[:16 * 1024]
    # The developer's own preview words, when set (template_preview.py).
    from core.services import template_preview              # noqa: PLC0415
    entry.update(template_preview.clean_copy(data))
    return key, entry


def save_format(key, data, config_dir=None):
    """Create or override one built-in format. Developer-gated at the route
    (and admin-gated for the template updater, which installs what a
    developer published). See format_entry for the validation."""
    key, entry = format_entry(key, data)
    # One read-modify-write under the lock. Two saves interleaving -- the
    # template updater installing several keys while a developer edits one,
    # or two admins pressing Check at once -- would otherwise each read the
    # file, each write it whole, and the second would drop the first's key.
    with _FORMATS_LOCK:
        formats = dict((config.load(FORMATS_FILE, config_dir) or {}).get("formats") or {})

        # Draft state. Explicit in `data` wins; otherwise an edit keeps what
        # the entry had, and a BRAND-NEW template starts as a draft -- the
        # developer moves it to built-in deliberately, so admins never see
        # half-built work.
        if "draft" in data:
            if data["draft"]:
                entry["draft"] = True
        elif (formats.get(key) or {}).get("draft"):
            entry["draft"] = True
        elif key not in TEMPLATES and key not in formats:
            entry["draft"] = True

        # The preview words survive a save that does not name them (Details,
        # a Publish refresh); naming them, even empty, sets them.
        for k in ("features", "blurb", "heading"):
            if k not in data and k in (formats.get(key) or {}):
                entry[k] = formats[key][k]
        formats[key] = entry
        _write_formats(formats, config_dir)
        return builtin_formats(config_dir)[key]


#: The one template that must ALWAYS be offered: the from-scratch path.
#: Every other template is a build somebody made and may unmake; this one is
#: the absence of a build, and a create picker without it has no way to start
#: empty at all. It cannot be deleted, hidden, or moved to drafts.
#:
#: It was "blank" while the code shipped a Blank Canvas of its own. Now the
#: blank canvas is published like every other template -- the developer box's
#: "Blank Canvas" system, whose slug `blank_canvas_template_editor` publishes
#: as this key (format_key) -- so the protection follows the key it has.
PROTECTED_FORMAT = "blank_canvas"


def set_format_draft(key, draft, config_dir=None):
    """Move a template between DRAFTS (developer-only) and BUILT-IN (offered
    to everyone in the create picker). The move is one flag, not a copy --
    label, workflow, widgets all stay put."""
    key = str(key or "").strip().lower()
    if draft and key == PROTECTED_FORMAT:
        raise ValueError("Blank Canvas is the from-scratch path - it is "
                         "always offered and cannot be moved to drafts")
    formats = dict((config.load(FORMATS_FILE, config_dir) or {}).get("formats") or {})
    if key not in formats and key not in TEMPLATES:
        raise ValueError("no such template " + repr(key))
    entry = dict(formats.get(key) or {})
    if draft:
        entry["draft"] = True
    else:
        entry.pop("draft", None)
    # A shipped template with an otherwise-empty entry needs no overlay row.
    if entry:
        formats[key] = entry
    else:
        formats.pop(key, None)
    _write_formats(formats, config_dir)
    return builtin_formats(config_dir).get(key)


def set_format_category(key, category, config_dir=None):
    """Refile a format under a category, everything else untouched.

    The systems grid's folders and the template panel's categories describe
    the same catalogue; moving a workbench system between folders calls this
    so the template follows, instead of the two views disagreeing about
    where one build lives.
    """
    key = str(key or "").strip().lower()
    formats = dict((config.load(FORMATS_FILE, config_dir) or {}).get("formats") or {})
    if key not in formats and key not in TEMPLATES:
        raise ValueError("no such template " + repr(key))
    entry = dict(formats.get(key) or {})
    entry["category"] = _format_category(category) if category \
        else DEFAULT_FORMAT_CATEGORY
    formats[key] = entry
    _write_formats(formats, config_dir)
    return builtin_formats(config_dir).get(key)


def delete_format(key, config_dir=None, hide_shipped=False):
    """Remove a format.

    Three outcomes, because there are three situations:

      * an AUTHORED format -> the entry goes, and it is gone.
      * a SHIPPED format, hide_shipped=False -> the override goes and the
        shipped version comes back. This is "undo my edits".
      * a SHIPPED format, hide_shipped=True -> a tombstone is written so it
        stops being offered. The code dict cannot be edited from a board, so a
        tombstone is the only honest way to delete one.

    Refuses to remove the LAST format either way: a box with nothing to create
    a system from is not a state any API should be able to produce.
    """
    key = str(key or "").strip().lower()
    if key == PROTECTED_FORMAT:
        raise ValueError("Blank Canvas is the from-scratch path - a picker "
                         "without it has no way to start empty, so it cannot "
                         "be deleted")
    formats = dict((config.load(FORMATS_FILE, config_dir) or {}).get("formats") or {})
    shipped = key in TEMPLATES

    if shipped and hide_shipped:
        if len([k for k in builtin_formats(config_dir) if k != key]) == 0:
            raise ValueError("this is the last format - a box needs at least "
                             "one to create a system from")
        entry = dict(formats.get(key) or {})
        entry[_HIDDEN_KEY] = True
        formats[key] = entry
        _write_formats(formats, config_dir)
        return {"reverted": False, "removed": False, "hidden": True}

    if key not in formats:
        raise ValueError("no authored format " + repr(key))
    if not shipped and len([k for k in builtin_formats(config_dir) if k != key]) == 0:
        raise ValueError("this is the last format - a box needs at least one "
                         "to create a system from")
    formats.pop(key)
    _write_formats(formats, config_dir)
    return {"reverted": shipped, "removed": not shipped, "hidden": False}


def restore_format(key, config_dir=None):
    """Bring a hidden shipped format back."""
    key = str(key or "").strip().lower()
    formats = dict((config.load(FORMATS_FILE, config_dir) or {}).get("formats") or {})
    entry = dict(formats.get(key) or {})
    if not entry.pop(_HIDDEN_KEY, None):
        raise ValueError("that format is not hidden")
    # An entry that held nothing but the tombstone goes entirely, so the
    # shipped version is served from code rather than from an empty override.
    if entry:
        formats[key] = entry
    else:
        formats.pop(key, None)
    _write_formats(formats, config_dir)
    return builtin_formats(config_dir).get(key)


def promote_template(key, doc, config_dir=None, category=None,
                     label=None, hint=None, zone=None, model=None):
    """Turn a snapshot/saved template into a built-in format.

    A saved template is one operator's finished build; a built-in is a starting
    point the product offers everyone. Promoting is how the first becomes the
    second -- the dashboard it was saved with becomes the format's starter
    dashboard, its class filter the seed classes, and its WORKFLOW travels
    whole, so a system created from the format starts with the same rules.

    `label`/`hint`/`zone`/`category` override what the doc carries -- the
    publish-back flow passes the format's existing ones so republishing a
    workbench never wipes the zone guidance a developer wrote.
    """
    doc = doc or {}
    layout = (doc.get("dashboard") or {})
    widgets = layout.get("widgets") if isinstance(layout, dict) else None
    if not widgets and isinstance(layout, dict):
        # snapshot_system saves the builder layout, which is paged -- the
        # format's starter dashboard is the main page's widgets.
        pages = [p for p in (layout.get("pages") or []) if isinstance(p, dict)]
        main = next((p for p in pages if p.get("id") == "main"), None) \
            or (pages[0] if pages else None)
        widgets = (main or {}).get("widgets")
    cfg = (doc.get("config") or {})
    detector = (cfg.get("detector") or {}) if isinstance(cfg, dict) else {}
    # snapshot_system writes config.detector_classes; older exports carried
    # config.detector.classes. Reading only the old spelling shipped formats
    # with an always-empty class filter.
    classes = (cfg.get("detector_classes") if isinstance(cfg, dict) else None) \
        or detector.get("classes") or (detector.get("hailo") or {}).get("classes")
    data = {
        "label": label or doc.get("name") or key,
        "hint": (hint if hint is not None else doc.get("description")) or "",
        "category": category or DEFAULT_FORMAT_CATEGORY,
        "classes": list(classes or []),
        "widgets": list(widgets or []),
    }
    # The model the workbench was RUNNING becomes the template's starting
    # model -- whoever built with it chose that model for a reason, and a
    # template that starts on a different one would not behave like the
    # system it was published from.
    if model is not None:
        data["model"] = model
    if isinstance(zone, dict):
        data["zone"] = zone
    if doc.get("workflows"):
        data["workflows"] = doc["workflows"]
    # The WHOLE dashboard layout, not just the main page's widgets: the
    # arrangement -- which page, where, how big -- is as much the build as
    # the widgets are, and the format path used to lose it (only `widgets`
    # travelled, and nothing read even those back on create).
    if isinstance(doc.get("dashboard"), dict) and doc["dashboard"]:
        data["dashboard"] = doc["dashboard"]
    # The dataset table definitions the workflow writes to -- names and column
    # types only, no data. Without them a landed Data Table names a table the
    # new box has never heard of.
    if doc.get("tables"):
        data["tables"] = doc["tables"]
    # The zones and on-system settings, so a created system is the WHOLE
    # build -- everything except recorded data.
    if doc.get("zones"):
        data["zones"] = doc["zones"]
    cfg = doc.get("config") or {}
    settings = {k: cfg[k] for k in ("capture", "hud")
                if isinstance(cfg.get(k), dict)}
    if settings:
        data["settings"] = settings
    return save_format(key, data, config_dir)


