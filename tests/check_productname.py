# -*- coding: utf-8 -*-
"""
check_productname.py -- the software is called "IRIV Edge AI Studio".

The owner renamed the product (2026-10-13) from "IRIV Vision Studio". The
name lives in a handful of places a customer sees: the browser tab, the
brand file every page reads, the shells' fallback when the brand is not yet
loaded, the test email/Telegram messages, the systemd unit descriptions. This
pins them, and fails when the old name creeps back into shipped code.

"IRIV Edge AI" on its own is the HARDWARE (the board) and is not checked
here. Three old-name strings stay on purpose and are allow-listed below,
each for a reason that outlives the rename.
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NEW = "IRIV Edge AI Studio"
OLD = "Vision Studio"

#: path -> why the old name may stay there.
ALLOWED_OLD = {
    # provision._GENERATED_MARKER: removal keys on this exact text, and every
    # generated package already on a box carries it.
    os.path.join("core", "services", "provision.py"): "builder marker",
    os.path.join("core", "services", "publish.py"): "builder marker",
    # A root helper, hash-pinned in the signed manifest; the header is a
    # comment inside /etc/mosquitto, seen by nobody in the UI.
    os.path.join("scripts", "mqtt_apply.py"): "root helper conf header",
}

bad = 0


def check(name, cond, detail=""):
    global bad
    print(("ok   " if cond else "FAIL ") + name + ("" if cond else "  -> %s" % detail))
    if not cond:
        bad += 1


def read(*parts):
    with open(os.path.join(ROOT, *parts), encoding="utf-8") as f:
        return f.read()


check("the page <title> is the new name",
      "<title>%s</title>" % NEW in read("frontend", "index.html"))
check("brand.toml names the product",
      'product_name = "%s"' % NEW in read("config", "brand.toml"))
for shell in ("HubShell.jsx", "MasterShell.jsx", "StandaloneShell.jsx"):
    check("%s falls back to the new name" % shell,
          'brand?.product_name || "%s"' % NEW in read("frontend", "src", "components", shell))
check("the login page falls back to the new name",
      'brand.product_name || "%s"' % NEW in read("frontend", "src", "pages", "Login.jsx"))
check("the mailbox test email says the new name",
      '"%s - mailbox test"' % NEW in read("core", "routes", "mail.py"))
check("the Telegram test message says the new name",
      "'%s test - the bot" % NEW in read("core", "routes", "telegram.py"))
check("the hub unit description says the new name",
      "Description=%s hub\n" % NEW in read("scripts", "install.sh"))
check("the builder marker is unchanged (removal keys on it)",
      '_GENERATED_MARKER = "generated by the IRIV Vision Studio builder"'
      in read("core", "services", "provision.py"))
check("the board card still names the hardware",
      "title={`IRIV Edge AI · " in read("frontend", "src", "components", "HealthPanel.jsx"))

# No old name anywhere else in shipped code.
SKIP_DIRS = {"node_modules", "dist", ".git", "docs", ".claude", "static", "tests", "__pycache__"}
EXTS = (".py", ".jsx", ".js", ".mjs", ".html", ".css", ".toml", ".json", ".sh",
        ".service", ".yml", ".md")
stray = []
for dirpath, dirnames, filenames in os.walk(ROOT):
    dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
    for fn in filenames:
        if not fn.endswith(EXTS):
            continue
        full = os.path.join(dirpath, fn)
        rel = os.path.relpath(full, ROOT)
        if rel in ALLOWED_OLD:
            continue
        try:
            with open(full, encoding="utf-8") as f:
                if OLD in f.read():
                    stray.append(rel)
        except (OSError, UnicodeDecodeError):
            continue
check("no stray old product name in shipped code", not stray, stray)

print()
if bad:
    print("%d check(s) failed" % bad)
    sys.exit(1)
print("all good")
